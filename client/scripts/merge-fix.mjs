/* global process */
/**
 * Công cụ xử lý xung đột nhanh cho tài sản và tài liệu sinh tự động (#1368, #1371).
 * Khi merge nhánh bị xung đột ở:
 * - BOOKS trong client/scripts/gen-assets.mjs (xung đột code: giải bằng tay giữ cả hai dòng)
 * - atlas.json / atlas.png / CREDITS.md / RA_SOAT_TAI_SAN.md (tài sản & tài liệu sinh tự động)
 *
 * Chạy lệnh: npm run assets:merge-fix
 * Lệnh này sẽ:
 * 1. Lấy bản sạch (checkout --ours) cho các tệp sinh tự động unmerged trước khi sinh
 * 2. Chạy lại `node client/scripts/gen-assets.mjs` để sinh lại atlas, icon và đồng bộ tài liệu từ danh sách đĩa
 * 3. Quét kiểm tra đảm bảo KHÔNG còn dấu xung đột git (<<<<<<<, =======, >>>>>>>) trong tài liệu & atlas
 * 4. Tự động `git add` các tệp đã sinh lại (chỉ khi hoàn toàn sạch dấu xung đột)
 */

import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, "../..");

process.stdout.write("[assets:merge-fix] Bắt đầu gỡ xung đột tài sản sinh tự động...\n");

// 1. Kiểm tra các tệp sinh tự động đang ở trạng thái unmerged để checkout --ours trước khi sinh
const autoGeneratedFiles = [
  "client/public/assets/atlas.json",
  "client/public/assets/atlas.png",
  "CREDITS.md",
  "docs/RA_SOAT_TAI_SAN.md",
];

try {
  let unmergedOutput = "";
  try {
    unmergedOutput = execSync("git diff --name-only --diff-filter=U", {
      cwd: ROOT_DIR,
      encoding: "utf8",
    });
  } catch {
    // không trong merge hoặc không có diff
  }

  const unmergedFiles = unmergedOutput
    .split("\n")
    .map((s) => s.trim())
    .filter(Boolean);

  for (const f of autoGeneratedFiles) {
    if (unmergedFiles.includes(f)) {
      process.stdout.write(`[assets:merge-fix] Khôi phục bản sạch cho ${f} (checkout --ours)...\n`);
      execSync(`git checkout --ours -- "${f}"`, { cwd: ROOT_DIR });
    }
  }
} catch (err) {
  process.stderr.write(`[assets:merge-fix] Cảnh báo khi checkout --ours: ${err.message}\n`);
}

try {
  // 2. Chạy lại sinh asset và đồng bộ tài liệu
  process.stdout.write("[assets:merge-fix] Đang chạy sinh lại tài sản và đồng bộ tài liệu...\n");
  execSync("node client/scripts/gen-assets.mjs", { cwd: ROOT_DIR, stdio: "inherit" });

  // 3. Quét kiểm tra dấu xung đột git còn sót lại trong các tệp sinh
  const filesToCheck = [
    path.resolve(ROOT_DIR, "CREDITS.md"),
    path.resolve(ROOT_DIR, "docs/RA_SOAT_TAI_SAN.md"),
    path.resolve(ROOT_DIR, "client/public/assets/atlas.json"),
  ];

  const conflictRegex = /^(<{7}|={7}|>{7})/m;
  const remainingConflicts = [];

  for (const file of filesToCheck) {
    if (fs.existsSync(file)) {
      const content = fs.readFileSync(file, "utf8");
      if (conflictRegex.test(content)) {
        remainingConflicts.push(path.relative(ROOT_DIR, file));
      }
    }
  }

  if (remainingConflicts.length > 0) {
    process.stderr.write(
      `[assets:merge-fix] LỖI CHẶN: Vẫn còn dấu xung đột git trong các tệp:\n` +
        remainingConflicts.map((f) => `  - ${f}`).join("\n") +
        `\nKhông thực hiện git add. Hãy kiểm tra và gỡ xung đột trước!\n`,
    );
    process.exit(1);
  }

  // 4. Tự động add các file sinh
  execSync("git add client/public/assets/ CREDITS.md docs/RA_SOAT_TAI_SAN.md", {
    cwd: ROOT_DIR,
    stdio: "inherit",
  });

  process.stdout.write(
    "✓ Đã gỡ xung đột và đồng bộ tài sản thành công! Các tệp đã được `git add` sẵn sàng commit.\n",
  );
} catch (err) {
  process.stderr.write(`[assets:merge-fix] Lỗi: ${err.message}\n`);
  process.exit(1);
}
